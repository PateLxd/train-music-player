/** merged playlist for a theme: theme tracks + its lofi tracks */
export function getPlaylist(themeId: string): Playlist {
  const base = PLAYLISTS[themeId];
  if (!base) return { themeId, stationLine: "", lofiIds: [], tracks: [] };
  const lofi = base.lofiIds
    .map((id) => LOFI_TRACKS.find((t) => t.id === id))
    .filter((t): t is Track => Boolean(t));
  return { ...base, tracks: [...base.tracks, ...lofi] };
}

